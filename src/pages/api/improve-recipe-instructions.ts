export async function POST(request: Request) {
  try {
    // Get all recipes from CMS
    const { items } = await BaseCrudService.getAll<HealthyRecipesandSnacks>('healthyrecipes');
    
    if (!items || items.length === 0) {
      return new Response(
        JSON.stringify({ message: 'Жор байхгүй байна' }),
        { status: 404 }
      );
    }

    let updatedCount = 0;
    const results = [];

    // Update each recipe with improved instructions
    for (const recipe of items) {
      const recipeName = recipe.recipeName || '';
      const improvedInstructions = IMPROVED_INSTRUCTIONS[recipeName];

      if (improvedInstructions) {
        try {
          await BaseCrudService.update<HealthyRecipesandSnacks>('healthyrecipes', {
            _id: recipe._id,
            instructions: improvedInstructions,
          });
          updatedCount++;
          results.push({
            recipeName,
            status: 'updated',
            message: `${recipeName} жорын заавар сайжруулагдлаа`,
          });
        } catch (err) {
          results.push({
            recipeName,
            status: 'error',
            message: `${recipeName} жорыг сайжруулахад алдаа гарлаа`,
            error: err instanceof Error ? err.message : 'Unknown error',
          });
        }
      } else {
        results.push({
          recipeName,
          status: 'skipped',
          message: `${recipeName} жорын сайжруулсан заавар олдсонгүй`,
        });
      }
    }

    return new Response(
      JSON.stringify({
        message: `${updatedCount} жорын заавар сайжруулагдлаа`,
        updatedCount,
        totalRecipes: items.length,
        results,
      }),
      { status: 200 }
    );
  } catch (error) {
    console.error('Error improving recipe instructions:', error);
    return new Response(
      JSON.stringify({
        message: 'Жорын заавар сайжруулахад алдаа гарлаа',
        error: error instanceof Error ? error.message : 'Unknown error',
      }),
      { status: 500 }
    );
  }
}
